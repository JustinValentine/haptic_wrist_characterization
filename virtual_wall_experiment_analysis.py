"""Virtual wall impact analysis: restitution, wall energy, rate-hardness.

Every impact is re-measured from the raw data with the same function the
experiment used online (virtual_wall_experiment.impact_metrics):

* coefficient of restitution e = |v_out| / |v_in|, from position slopes just
  before entry and just after the wall torque releases (a delayed wall keeps
  pushing past exit) (e > 1: the wall launched the handle back
  faster than it arrived, i.e. it injected energy; physical walls give e < 1);
* wall work = integral of the measured wall torque over the penetration
  (positive = energy generated by the rendering itself, independent of the
  joint's friction), also as a percentage of the impact energy 0.5 J v_in^2;
* rate-hardness: the rate of rise of the wall torque over the first quarter
  of the contact per unit impact speed (Lawrence et al., IEEE Trans. Robot.
  Autom. 16(4), 2000); close to K for a delay-free spring (10-15% low in
  simulation from the curvature of the torque rise and the current-loop lag),
  raised by damping, lowered by a delayed torque onset;
* effective torque delay (line through the 10-50% torque rise, extrapolated to
  zero), how long the wall keeps pushing after the handle has left (torque
  release), effective stiffness (torque / penetration at the deepest point),
  peak penetration, contact time, and the number of contacts.

Results are aggregated per (mode, B, impact speed, K). The paper figures use
the reference damping (B = 0 when tested) and the fastest impact speed.

Run:  python virtual_wall_experiment_analysis.py [run_dir] [--no-show]
"""
import math

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from analysis_common import (export_figure, load_run, make_parser, print_header, save_outputs,
                             sim_truth)
from ieee_plot import (INK, SERIES, TORQUE_UNIT, add_panel_label, configure_ieee_style,
                       figure_size, log_ticks_hz, pad_top_tick, reference_line, series_style,
                       style_axis, zero_line)
from virtual_wall_experiment import EXPERIMENT, UNSTABLE_REASONS, impact_metrics

FIGURE_BASENAME = 'fig_virtual_wall'
HARDNESS_BASENAME = 'fig_virtual_wall_hardness'
DIAGNOSTIC_BASENAME = 'diag_virtual_wall_impacts'
REFERENCE_K = 100.0          # Stiffness used for the headline numbers and the example loops
METRICS = ['restitution', 'wall_work_mj', 'wall_energy_gain_percent', 'rate_hardness_nm_rad',
           'k_eff_nm_rad', 'torque_delay_ms', 'torque_release_ms', 'peak_penetration_deg',
           'contact_ms',
           'peak_torque_nm', 'v_in_deg_s', 'v_out_deg_s', 'wall_work_balance_mj',
           'num_contacts']


def mode_label(name):
    if name == 'rt':
        return '500 Hz loop wall'
    if name.startswith('host_'):
        rate = float(name.split('_', 1)[1])
        return f'Host loop, {rate / 1000:g} kHz' if rate >= 1000 else f'Host loop, {rate:g} Hz'
    return name


def reference(run):
    proto = run.meta.get('virtual_wall_protocol') or {}
    ref = proto.get('reference') or {}
    return (float(ref.get('inertia', 0.008)), float(ref.get('coulomb', 0.0)),
            float(ref.get('viscous', 0.0)), ref.get('source', 'unknown'))


def measure_impacts(run):
    df = run.df
    inertia, coulomb, viscous, _ = reference(run)
    online = {int(r['trial_id']): r for r in run.meta.get('impacts', [])}
    max_contacts = int((run.meta.get('experiment_config') or {}).get('max_contacts', 4))
    wall = df[df['phase'] == 'wall']
    rows = []
    for trial_id, frame in wall.groupby('trial_id', sort=True):
        trial_id = int(trial_id)
        frame = frame.sort_values('time')
        wall_deg = float(frame['wall_deg'].iloc[0])
        metrics = impact_metrics(frame['t_local'], frame['joint_pos_deg'],
                                 frame['joint_torque_nm'], wall_deg, inertia, coulomb, viscous)
        ended_by = online.get(trial_id, {}).get('ended_by', '')
        rows.append({
            'trial_id': trial_id,
            'mode': str(frame['render_mode'].iloc[0]),
            'virtual_k_nm_rad': float(frame['virtual_k_nm_rad'].iloc[0]),
            'virtual_b_nms_rad': float(frame['virtual_b_nms_rad'].iloc[0]),
            'impact_speed_deg_s': float(frame['impact_speed_deg_s'].iloc[0]),
            'repeat': int(frame['repeat'].iloc[0]),
            'ended_by': ended_by,
            'unstable': bool(ended_by in UNSTABLE_REASONS
                             or metrics['num_contacts'] > max_contacts),
            **metrics,
        })
    impacts = pd.DataFrame(rows)
    if not impacts.empty:
        impacts['rate_hardness_ratio'] = impacts['rate_hardness_nm_rad'] / impacts['virtual_k_nm_rad']
        impacts['k_eff_ratio'] = impacts['k_eff_nm_rad'] / impacts['virtual_k_nm_rad']
    return impacts


def condition_table(impacts):
    keys = ['mode', 'virtual_b_nms_rad', 'impact_speed_deg_s', 'virtual_k_nm_rad']
    ok = impacts[impacts['contact']]
    grouped = ok.groupby(keys, sort=True)
    table = grouped[METRICS].agg(['mean', 'std'])
    table.columns = [f'{m}_{s}' for m, s in table.columns]
    table = table.reset_index()
    table['num_impacts'] = grouped.size().to_numpy()
    table['num_unstable'] = grouped['unstable'].sum().to_numpy()
    return table


def reference_conditions(conditions, modes):
    """(B, speed, K) for the headline numbers: B = 0 if tested, fastest speed,
    and the stiffness closest to REFERENCE_K that every mode has."""
    b_ref = 0.0 if (conditions['virtual_b_nms_rad'] == 0).any() else float(
        conditions['virtual_b_nms_rad'].min())
    sub = conditions[conditions['virtual_b_nms_rad'] == b_ref]
    v_ref = float(sub['impact_speed_deg_s'].max())
    sub = sub[sub['impact_speed_deg_s'] == v_ref]
    common = None
    for mode in modes:
        ks = set(sub.loc[sub['mode'] == mode, 'virtual_k_nm_rad'])
        common = ks if common is None else common & ks
    pool = sorted(common) if common else sorted(set(sub['virtual_k_nm_rad']))
    k_ref = min(pool, key=lambda k: abs(math.log(k / REFERENCE_K)))
    return b_ref, v_ref, float(k_ref), sub


def passivity_limits(sub, mode):
    """Largest K with mean e < 1 before the first K with e >= 1 (and that K)."""
    rows = sub[sub['mode'] == mode].sort_values('virtual_k_nm_rad')
    last_passive, first_active = math.nan, math.nan
    for _, r in rows.iterrows():
        e = r['restitution_mean']
        if not math.isfinite(e):
            continue
        if e < 1.0:
            last_passive = r['virtual_k_nm_rad']
        else:
            first_active = r['virtual_k_nm_rad']
            break
    lower_bound = math.isnan(first_active) and not math.isnan(last_passive)
    return last_passive, first_active, lower_bound


def summarize(impacts, conditions, modes):
    b_ref, v_ref, k_ref, sub = reference_conditions(conditions, modes)
    summary = {
        'num_impacts': int(len(impacts)),
        'num_contacts_measured': int(impacts['contact'].sum()),
        'num_unstable': int(impacts['unstable'].sum()),
        'reference_k_nm_rad': k_ref,
        'reference_b_nms_rad': b_ref,
        'reference_speed_deg_s': v_ref,
    }
    for mode in modes:
        row = sub[(sub['mode'] == mode) & (sub['virtual_k_nm_rad'] == k_ref)]
        if len(row):
            r = row.iloc[0]
            summary.update({
                f'restitution_{mode}_kref': r['restitution_mean'],
                f'restitution_{mode}_kref_sd': r['restitution_std'],
                f'wall_energy_gain_{mode}_kref_percent': r['wall_energy_gain_percent_mean'],
                f'rate_hardness_{mode}_kref_nm_rad': r['rate_hardness_nm_rad_mean'],
                f'rate_hardness_ratio_{mode}_kref': r['rate_hardness_nm_rad_mean'] / k_ref,
                f'k_eff_{mode}_kref_nm_rad': r['k_eff_nm_rad_mean'],
                f'torque_delay_{mode}_kref_ms': r['torque_delay_ms_mean'],
                f'torque_release_{mode}_kref_ms': r['torque_release_ms_mean'],
                f'peak_penetration_{mode}_kref_deg': r['peak_penetration_deg_mean'],
            })
        last_passive, first_active, lower_bound = passivity_limits(sub, mode)
        summary[f'max_passive_k_{mode}_nm_rad'] = last_passive
        summary[f'max_passive_k_{mode}_is_lower_bound'] = bool(lower_bound)
        summary[f'first_active_k_{mode}_nm_rad'] = first_active
        delays = impacts.loc[(impacts['mode'] == mode) & impacts['contact'], 'torque_delay_ms']
        summary[f'torque_delay_{mode}_median_ms'] = float(delays.median()) if len(delays) else math.nan
    return summary, sub


# --- figures -------------------------------------------------------------------------------
def example_impacts(run, impacts, modes, b_ref, v_ref, k_ref):
    picks = {}
    for mode in modes:
        cand = impacts[(impacts['mode'] == mode) & (impacts['virtual_k_nm_rad'] == k_ref)
                       & (impacts['virtual_b_nms_rad'] == b_ref)
                       & (impacts['impact_speed_deg_s'] == v_ref) & impacts['exited']]
        if len(cand):
            picks[mode] = cand.sort_values('repeat').iloc[0]
    frames = {}
    df = run.df
    for mode, impact in picks.items():
        frame = df[(df['phase'] == 'wall') & (df['trial_id'] == impact['trial_id'])].sort_values('time')
        frames[mode] = (impact, frame)
    return frames


def contact_window(impact, frame, pad_s=0.0015):
    """Entry to the release of the wall torque (which a delayed wall holds past exit)."""
    t = frame['t_local'].to_numpy()
    release = impact['torque_release_ms'] if math.isfinite(impact['torque_release_ms']) else 0.0
    sel = (t >= impact['t_in_s'] - pad_s) & (t <= impact['t_out_s'] + 1e-3 * release + pad_s)
    return frame[sel]


def plot_wall(examples, sub, modes, k_ref, v_ref):
    fig, (ax_l, ax_e) = plt.subplots(2, 1, figsize=figure_size('single', 4.0),
                                     gridspec_kw={'height_ratios': [1.1, 1.0], 'hspace': 0.42})
    for i, mode in enumerate(modes):
        if mode not in examples:
            continue
        impact, frame = examples[mode]
        win = contact_window(impact, frame)
        pen = win['joint_pos_deg'] - float(frame['wall_deg'].iloc[0])
        push = -win['joint_torque_nm']
        gain = impact['wall_energy_gain_percent']
        ax_l.plot(pen, push, color=SERIES[i], linestyle='-' if i == 0 else '--', linewidth=1.0,
                  label=f"{mode_label(mode)}: e = {impact['restitution']:.2f}, "
                        f"wall work {gain:+.0f}%")
    zero_line(ax_l)
    zero_line(ax_l, orientation='v')
    ax_l.set_xlabel('Penetration (deg)')
    ax_l.set_ylabel(f'Wall torque ({TORQUE_UNIT})')
    style_axis(ax_l)
    lo, hi = ax_l.get_ylim()
    ax_l.set_ylim(lo, hi + 0.42 * (hi - lo))
    ax_l.legend(loc='upper left', fontsize=6.5, title=f'K = {k_ref:g} {TORQUE_UNIT}/rad, '
                f'{v_ref:g} deg/s; counter-clockwise loop = energy injected',
                title_fontsize=6.5)
    pad_top_tick(ax_l)
    add_panel_label(ax_l, '(a)', x=-0.12)

    for i, mode in enumerate(modes):
        rows = sub[sub['mode'] == mode].sort_values('virtual_k_nm_rad')
        if rows.empty:
            continue
        ax_e.errorbar(rows['virtual_k_nm_rad'], rows['restitution_mean'],
                      yerr=rows['restitution_std'].fillna(0.0), label=mode_label(mode),
                      elinewidth=0.6, **series_style(i))
    reference_line(ax_e, 1.0, label='$e$ = 1 (no net energy change)')
    ax_e.set_xscale('log')
    log_ticks_hz(ax_e)
    ax_e.set_xlabel(f'Wall stiffness $K$ ({TORQUE_UNIT}/rad)')
    ax_e.set_ylabel('Coefficient of restitution $e$')
    style_axis(ax_e)
    lo, hi = ax_e.get_ylim()
    ax_e.set_ylim(min(lo, 0.5), hi + 0.35 * (hi - lo))
    ax_e.legend(loc='upper left', fontsize=6.5)
    pad_top_tick(ax_e)
    add_panel_label(ax_e, '(b)', x=-0.12)
    return fig


def plot_hardness(sub, modes, v_ref):
    """(a) rate-hardness relative to the commanded stiffness; (b) wall energy gain."""
    fig, (ax_h, ax_w) = plt.subplots(2, 1, figsize=figure_size('single', 3.9), sharex=True,
                                     gridspec_kw={'hspace': 0.15})
    ks = np.array(sorted(sub['virtual_k_nm_rad'].unique()))
    for i, mode in enumerate(modes):
        rows = sub[sub['mode'] == mode].sort_values('virtual_k_nm_rad')
        if rows.empty:
            continue
        k = rows['virtual_k_nm_rad'].to_numpy()
        ax_h.errorbar(k, rows['rate_hardness_nm_rad_mean'] / k,
                      yerr=rows['rate_hardness_nm_rad_std'].fillna(0.0) / k,
                      label=mode_label(mode), elinewidth=0.6, **series_style(i))
        ax_w.errorbar(k, rows['wall_energy_gain_percent_mean'],
                      yerr=rows['wall_energy_gain_percent_std'].fillna(0.0),
                      elinewidth=0.6, **series_style(i))
    reference_line(ax_h, 1.0, label='Rate-hardness = $K$')
    ax_h.set_xscale('log')
    ax_h.set_xlim(ks.min() / 1.3, ks.max() * 1.3)
    log_ticks_hz(ax_h)
    ax_h.set_ylim(min(0.0, ax_h.get_ylim()[0]), 1.45)
    ax_h.set_ylabel('Rate-hardness / $K$')
    style_axis(ax_h, minor=False)
    ax_h.legend(loc='lower left', fontsize=6.5)
    add_panel_label(ax_h, '(a)', x=-0.12)

    zero_line(ax_w)
    ax_w.set_xlabel(f'Wall stiffness $K$ ({TORQUE_UNIT}/rad)')
    ax_w.set_ylabel('Wall energy gain (%)')
    style_axis(ax_w, minor=False)
    ax_w.text(0.02, 0.95, f'> 0: rendering injects energy ({v_ref:g} deg/s impacts)',
              transform=ax_w.transAxes, ha='left', va='top', fontsize=6.5, color=INK)
    lo, hi = ax_w.get_ylim()
    ax_w.set_ylim(lo, hi + 0.2 * (hi - lo))
    add_panel_label(ax_w, '(b)', x=-0.12)
    fig.align_ylabels([ax_h, ax_w])
    return fig


def plot_examples(examples, modes):
    fig, axes = plt.subplots(2, max(len(examples), 1), figsize=figure_size('double', 3.0),
                             squeeze=False, sharex='col')
    for col, mode in enumerate([m for m in modes if m in examples]):
        impact, frame = examples[mode]
        t0 = impact['t_in_s']
        t = 1e3 * (frame['t_local'] - t0)
        window = (t >= -20) & (t <= 1e3 * (impact['t_out_s'] - t0) + 40)
        wall = float(frame['wall_deg'].iloc[0])
        axes[0, col].plot(t[window], frame['joint_pos_deg'][window] - wall, color=INK, linewidth=0.8)
        zero_line(axes[0, col])
        axes[1, col].plot(t[window], -frame['joint_torque_nm'][window], color=INK, linewidth=0.8)
        axes[0, col].set_title(f"{mode_label(mode)}: K = {impact['virtual_k_nm_rad']:g}, "
                               f"e = {impact['restitution']:.2f}, delay "
                               f"{impact['torque_delay_ms']:.1f} ms", fontsize=7)
        axes[1, col].set_xlabel('Time from contact (ms)')
        for ax in axes[:, col]:
            style_axis(ax, minor=False)
    axes[0, 0].set_ylabel('Penetration (deg)')
    axes[1, 0].set_ylabel(f'Wall torque ({TORQUE_UNIT})')
    fig.tight_layout(pad=0.3)
    return fig


# --- main ------------------------------------------------------------------------------
def main(argv=None):
    args = make_parser(__doc__.splitlines()[0]).parse_args(argv)
    configure_ieee_style()
    run = load_run(EXPERIMENT, args.data)
    impacts = measure_impacts(run)
    if impacts.empty or not impacts['contact'].any():
        raise SystemExit('No wall contacts found in this run.')
    modes = list(dict.fromkeys(impacts['mode']))
    conditions = condition_table(impacts)
    summary, sub = summarize(impacts, conditions, modes)
    inertia, coulomb, viscous, source = reference(run)
    summary.update({'J_reference_kg_m2': inertia, 'J_reference_source': source})
    proto = run.meta.get('virtual_wall_protocol') or {}
    metadata = {
        'analysis': 'virtual_wall_experiment_analysis.py',
        'source_data': str(run.source),
        'method': ('per impact: restitution from position slopes over '
                   f"{proto.get('vel_window_s', 0.005) * 1e3:g} ms before entry/after exit; "
                   'wall work = integral of measured torque over penetration; rate-hardness = '
                   'torque rise through the contact point over the first quarter of the contact '
                   'per unit impact speed (Lawrence et al. 2000)'),
        'reference_condition': {'k_nm_rad': summary['reference_k_nm_rad'],
                                'b_nms_rad': summary['reference_b_nms_rad'],
                                'speed_deg_s': summary['reference_speed_deg_s']},
        'energy_reference': {'J_kg_m2': inertia, 'coulomb_nm': coulomb,
                             'viscous_nms_rad': viscous, 'source': source},
        'note': ('Unloaded impacts (handle free). Torques are in the torque scale the drives '
                 'reports; e and the wall-work percentage are scale-free ratios. '
                 'wall_work_balance_mj (kinetic energy change + modeled friction loss) is a '
                 'model-based cross-check of the directly integrated wall work.'),
    }
    save_outputs(run, {'impacts': impacts, 'conditions': conditions}, summary, metadata)

    print_header('VIRTUAL WALL IMPACTS')
    print(f"Impacts: {summary['num_impacts']} ({summary['num_contacts_measured']} with contact, "
          f"{summary['num_unstable']} unstable); energy terms use J = {inertia:.4g} kg m^2 "
          f'({source})')
    print(f"Reference: K = {summary['reference_k_nm_rad']:g} N m/rad, "
          f"B = {summary['reference_b_nms_rad']:g} N m s/rad, "
          f"{summary['reference_speed_deg_s']:g} deg/s")
    for mode in modes:
        print(f'  {mode_label(mode)}')
        for _, r in sub[sub['mode'] == mode].sort_values('virtual_k_nm_rad').iterrows():
            print(f"    K {r['virtual_k_nm_rad']:7.4g}: e {r['restitution_mean']:.2f}"
                  f" (SD {r['restitution_std']:.2f}), wall work {r['wall_energy_gain_percent_mean']:+6.1f}%,"
                  f" RH {r['rate_hardness_nm_rad_mean']:7.1f} N m/rad,"
                  f" K_eff {r['k_eff_nm_rad_mean']:7.1f}, delay {r['torque_delay_ms_mean']:+.2f} ms,"
                  f" penetration {r['peak_penetration_deg_mean']:.2f} deg")
        bound = '>=' if summary[f'max_passive_k_{mode}_is_lower_bound'] else ''
        print(f"    Largest passive K (e < 1): {bound}{summary[f'max_passive_k_{mode}_nm_rad']:.4g} "
              f"N m/rad; first active K: {summary[f'first_active_k_{mode}_nm_rad']:.4g} N m/rad; "
              f"median torque delay {summary[f'torque_delay_{mode}_median_ms']:.2f} ms")
    if sim_truth(run):
        print('Simulated run: no closed-form truth for restitution; expect 500 Hz loop walls with '
              'e < 1 and host-loop walls with e > 1 once K x loop delay exceeds the damping.')

    examples = example_impacts(run, impacts, modes, summary['reference_b_nms_rad'],
                               summary['reference_speed_deg_s'], summary['reference_k_nm_rad'])
    fig = plot_wall(examples, sub, modes, summary['reference_k_nm_rad'],
                    summary['reference_speed_deg_s'])
    paths = export_figure(fig, run, FIGURE_BASENAME, {**metadata, **summary}, args.paper_dir)
    fig = plot_hardness(sub, modes, summary['reference_speed_deg_s'])
    export_figure(fig, run, HARDNESS_BASENAME, {**metadata, **summary}, args.paper_dir)
    if examples:
        export_figure(plot_examples(examples, modes), run, DIAGNOSTIC_BASENAME, metadata,
                      paper_dir='')
    print(f"Saved results to {run.out_dir}; paper figure {paths['pdf']}")
    if args.no_show:
        plt.close('all')
    else:
        plt.show()
    return summary


if __name__ == '__main__':
    main()
